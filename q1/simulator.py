"""Physical simulator and simulator-only intervention oracle for Q1."""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Iterable

import numpy as np
from numpy.typing import NDArray

FloatArray = NDArray[np.float64]
Program = tuple[int, ...]
PROGRAMS: tuple[Program, ...] = ((),) + tuple((i,) for i in range(4)) + tuple(
    (i, j) for i in range(4) for j in range(4)
)


@dataclass(frozen=True)
class DynamicsParams:
    B: FloatArray
    d: float
    b: float
    kappa: float

    def __post_init__(self) -> None:
        matrix = np.asarray(self.B, dtype=np.float64)
        if matrix.shape != (2, 2) or not np.isfinite(matrix).all():
            raise ValueError("B must be a finite 2x2 matrix")
        if abs(float(np.linalg.det(matrix))) < 1e-8:
            raise ValueError("B must be invertible")
        if min(self.d, self.b, self.kappa) <= 0 or not np.isfinite(
            [self.d, self.b, self.kappa]
        ).all():
            raise ValueError("d, b, and kappa must be finite and positive")
        object.__setattr__(self, "B", matrix.copy())


def transition(
    state: FloatArray,
    action: FloatArray,
    params: DynamicsParams,
    *,
    dt: float = 0.05,
    sigma: float = 0.0,
    rng: np.random.Generator | None = None,
) -> FloatArray:
    """One transition. Noise affects velocity only; position uses new velocity."""
    state = np.asarray(state, dtype=np.float64)
    action = np.asarray(action, dtype=np.float64)
    if state.shape != (4,) or action.shape != (2,):
        raise ValueError("state/action shapes must be (4,) and (2,)")
    if dt <= 0 or sigma < 0 or not np.isfinite(state).all() or not np.isfinite(action).all():
        raise ValueError("invalid dt, sigma, state, or action")
    q, v = state[:2], state[2:]
    u = np.tanh(params.B @ action) - params.d * v - params.b * np.linalg.norm(v) * v - params.kappa * q
    eps = np.zeros(2, dtype=np.float64) if sigma == 0 else (rng or np.random.default_rng()).normal(0.0, sigma, 2)
    v_next = v + dt * u + eps
    q_next = q + dt * v_next
    result = np.concatenate((q_next, v_next))
    if not np.isfinite(result).all():
        raise FloatingPointError("non-finite state generated by simulator")
    return result


def intervention(params: DynamicsParams, code: int) -> DynamicsParams:
    """Apply one simulator-only U1..U4 intervention (codes are zero-based)."""
    if code not in range(4):
        raise ValueError("intervention code must be in [0, 3]")
    if code == 0:
        angle = np.pi / 6
        rotation = np.array([[np.cos(angle), -np.sin(angle)], [np.sin(angle), np.cos(angle)]])
        return replace(params, B=rotation @ params.B)
    if code == 1:
        return replace(params, B=np.diag([1.5, 1.0]) @ params.B)
    if code == 2:
        return replace(params, d=1.4 * params.d)
    return replace(params, b=1.5 * params.b)


def apply_program(params: DynamicsParams, program: Program) -> DynamicsParams:
    """Apply codes in listed order; (i,j) means Ui followed by Uj."""
    updated = params
    for code in program:
        updated = intervention(updated, code)
    return updated


def sample_params(rng: np.random.Generator, region: str = "train",
                  parameter_ranges: dict | None = None) -> DynamicsParams:
    """Sample declared backgrounds; OOD regions use disjoint parameter bins."""
    ranges = parameter_ranges or {
        "train": ((0.75, 1.0), (0.28, 0.42), (0.08, 0.14), (0.18, 0.28)),
        "validation": ((1.03, 1.17), (0.45, 0.55), (0.15, 0.19), (0.30, 0.36)),
        "test_id": ((0.86, 0.96), (0.33, 0.39), (0.10, 0.13), (0.21, 0.26)),
        "test_background_ood": ((1.22, 1.38), (0.60, 0.72), (0.21, 0.27), (0.39, 0.47)),
    }
    if region not in ranges:
        raise ValueError(f"unknown parameter region: {region}")
    if isinstance(ranges[region], dict):
        spec = ranges[region]
        diagonal = spec["B_diag"]
        off_diagonal = spec["B_offdiag"]
        dr, br, kr = spec["d"], spec["b"], spec["kappa"]
        lo, hi = diagonal
        B = np.array([[rng.uniform(lo, hi), rng.uniform(*off_diagonal)],
                      [rng.uniform(*off_diagonal), rng.uniform(lo, hi)]])
        return DynamicsParams(B, rng.uniform(*dr), rng.uniform(*br), rng.uniform(*kr))
    (lo, hi), dr, br, kr = ranges[region]
    # A modest off-diagonal term preserves invertibility and varied action responses.
    B = np.array([[rng.uniform(lo, hi), rng.uniform(-0.12, 0.12)],
                  [rng.uniform(-0.12, 0.12), rng.uniform(lo, hi)]])
    return DynamicsParams(B, rng.uniform(*dr), rng.uniform(*br), rng.uniform(*kr))


def enumerate_programs() -> tuple[Program, ...]:
    return PROGRAMS


def response(params: DynamicsParams, probes: FloatArray, *, dt: float = 0.05) -> FloatArray:
    """Deterministic delta-v response on [state(4), action(2)] probes."""
    probes = np.asarray(probes, dtype=np.float64)
    if probes.ndim != 2 or probes.shape[1] != 6:
        raise ValueError("probes must have shape (n, 6)")
    rows = []
    for row in probes:
        state, action = row[:4], row[4:]
        next_state = transition(state, action, params, dt=dt)
        rows.append(next_state[2:] - state[2:])
    return np.asarray(rows)

